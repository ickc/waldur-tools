"""What ends up inside the release archive.

`scripts/pack_web.py` runs once, in the release workflow, on a tag -- so nothing
else exercises it and a mistake in it is found by whoever downloads the zip.
Two things about it are worth pinning: that the licence travels with the code,
since the archive is how most people who use the extension ever receive it, and
that the archive is reproducible, which is the reason for the fixed timestamp
and the sorted entries.

The tests build their own tree rather than reading `web/`. `web/vendor/` is
generated by `pixi run web-vendor` and gitignored, so in a fresh checkout -- and
in CI, where `check` runs before the vendoring step -- it does not exist.
"""

from __future__ import annotations

import importlib.util
import json
import zipfile
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]


def load():
    """Import the script by path: `scripts/` is not a package and not installed."""
    spec = importlib.util.spec_from_file_location("pack_web", ROOT / "scripts" / "pack_web.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture
def tree(tmp_path):
    """A repository shaped like this one, small enough to assert on whole.

    Written with `newline="\n"` throughout, because the real repository's
    `.gitattributes` is `* text=auto eol=lf` and so hands every platform a
    working tree with LF in it -- which is what keeps the archive reproducible
    across machines. Letting the platform translate here would model a checkout
    this project does not have, and the assertions below are on bytes.
    """
    web = tmp_path / "web"
    (web / "src").mkdir(parents=True)
    (web / "vendor").mkdir()

    def write(path, text):
        path.write_text(text, encoding="utf-8", newline="\n")

    write(web / "manifest.json", json.dumps({"version": "9.9.9"}))
    write(web / "README.md", "readme\n")
    write(web / "src" / "report.js", "// code\n")
    write(web / "vendor" / "plotly.min.js", "// plotly\n")
    write(web / "vendor" / "plotly.LICENSE", "MIT License\n")
    # Developer scaffolding, which must stay out of the archive.
    (web / "tests").mkdir()
    write(web / "tests" / "parity.test.mjs", "// tests\n")
    write(web / "package.json", "{}\n")
    write(tmp_path / "LICENSE", "BSD 3-Clause License\n")
    return tmp_path


def packed(module, tree):
    """Run `main` against `tree` and hand back the archive it wrote."""
    module.ROOT = tree
    module.WEB = tree / "web"
    module.DIST = tree / "dist"
    module.main()
    return zipfile.ZipFile(tree / "dist" / "isambard-utilisation-9.9.9.zip")


def test_the_licence_ships_inside_the_archive(tree):
    """The zip is a redistribution, and most of its readers never see the repo."""
    module = load()
    with packed(module, tree) as archive:
        assert archive.read("LICENSE").decode() == "BSD 3-Clause License\n"


def test_plotly_s_licence_ships_beside_its_bundle(tree):
    """`plotly.min.js` names the MIT licence but does not carry its text."""
    module = load()
    with packed(module, tree) as archive:
        assert archive.read("vendor/plotly.LICENSE").decode() == "MIT License\n"


def test_a_missing_plotly_licence_stops_the_release(tree):
    module = load()
    (tree / "web" / "vendor" / "plotly.LICENSE").unlink()
    with pytest.raises(SystemExit, match=r"plotly\.LICENSE is missing"):
        packed(module, tree)


def test_the_licence_lands_at_the_root_beside_the_manifest(tree):
    """It comes from outside `web/`, so it is the one entry whose path is invented."""
    module = load()
    with packed(module, tree) as archive:
        top = sorted(name for name in archive.namelist() if "/" not in name)
    assert top == ["LICENSE", "README.md", "manifest.json"]


def test_developer_scaffolding_stays_out(tree):
    module = load()
    with packed(module, tree) as archive:
        names = archive.namelist()
    assert not any(name.startswith("tests/") for name in names)
    assert "package.json" not in names


def test_a_missing_licence_stops_the_release_rather_than_shipping_without_it(tree):
    module = load()
    (tree / "LICENSE").unlink()
    with pytest.raises(SystemExit, match="LICENSE is missing"):
        packed(module, tree)


def test_the_archive_is_reproducible(tree):
    """Sorted entries and a fixed timestamp, so two builds compare byte for byte.

    The licence is what made this worth re-checking: entries are now sorted on
    the name inside the archive rather than on the source path, because those
    two stopped agreeing the moment one file came from outside `web/`.
    """
    module = load()
    with packed(module, tree) as archive:
        first = archive.namelist()
    built = (tree / "dist" / "isambard-utilisation-9.9.9.zip").read_bytes()

    with packed(module, tree) as archive:
        assert archive.namelist() == sorted(first)
    assert (tree / "dist" / "isambard-utilisation-9.9.9.zip").read_bytes() == built
